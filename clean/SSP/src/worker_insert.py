async def worker_insert(
        redis: aioredis.Redis,
        batch_size: int = 500,
        interval_sec: int = 2
):
    if redis is None:
        logger.info("Redis is None")
        return

    try:
        await redis.xgroup_create("auction:to_process", "insert_workers", id="0", mkstream=True)
    except Exception as e:
        if "BUSYGROUP" not in str(e):
            raise
    try:
        async with SessionLocal() as db:
            auc_stage_table = AuctionStage.__table__
            auc_main_table = Auction.__table__
            bid_stage_table = BidStage.__table__
            bid_main_table = Bid.__table__
            columns_auction = Auction.__table__.columns.keys()
            columns_bid = Bid.__table__.columns.keys()
            columns_bid.remove("id")#since it is generated by postgres itself
            print(columns_auction, columns_bid)
    except Exception as e:
        logger.error("Failed to get columns")
        raise
        # Read up to `batch_size` new jobs for this specific worker
        # ">" means "undelivered messages"
    while True:
        try:
            jobs = await redis.xreadgroup(
                groupname="insert_workers",
                consumername="worker_1",
                streams={"auction:to_process": ">"},
                count=batch_size,
                block=interval_sec*1000
            )
        except Exception as e:
            logger.error(f"Failed to fetch jobs from redis stream")
            raise
        if not jobs:
            continue
        try:
            job_ids, auctions, bids = await process_jobs(jobs, columns_auction, columns_bid) 
        except Exception as e:
            logger.error(f"Failed to process jobs")
            raise
        try:
            async with await psycopg.AsyncConnection.connect(CONNINFO) as conn:
                logger.error(f"conn type: {type(conn)}")
                await bulk_copy_to_stage(auc_stage_table, columns_auction, auctions, conn)
                await bulk_copy_to_stage(bid_stage_table, columns_bid, bids, conn)
        except Exception as e:
            logger.error(f"Failed insert into stage table")
            raise
        try:
            await redis.xack("auction:to_process", "insert_workers", *job_ids)
        except Exception as e:
            logger.error(f"failed to xack")
            raise


async def bulk_copy_to_stage(
        table: str,
        columns: list[str],
        data: list[tuple],
        conn: psycopg.AsyncConnection
):
    """
    Loads data into a raw table using COPY.
    'data' is a list of tuples, e.g., [(val1, val2), (val3, val4)].
    """
    # each tuple is ordered as columns are
    col_names = ", ".join(columns)
    copy_sql = f"COPY {table} ({col_names}) FROM STDIN"
    
    async with conn.cursor() as cur:
        # The copy() method returns a context manager
        async with cur.copy(copy_sql) as copy:
            for row in data:
                # write_row handles the adaptation of Python types
                await copy.write_row(row)
    # Commit the transaction after the COPY is done
    await conn.commit()

async def process_jobs(jobs, columns_auction, columns_bid) -> tuple[list, list, list]:
# jobs description:
# list[list[str, list[tuple[str, dict[str:dict]]]]]
# jobs: list[
#     job: list[
#         stream_name:str, -- first argument of our xadd, e.g. "auction:to_process
#         messages: list[
#             message: tuple(
#                 job_id: str,-- assigned by redis
#                 data: dict[ -- this is what we pushed with xadd
#                     "auction_data": dumped json of a singe auction data
#                     "bid data": dumped json of multiple bids related to the auc above
#                     When these are loaded with json, they each become a list of dicts:
#                     auction data containing a single element of dict, and bid_data turns into list of multiple dicts if any
#                 ]
#             )
#         ]]]

    auctions = []
    bids = []
    job_ids = []
    for stream_name, messages in jobs:
        for job_id, data in messages:
            job_ids.append(job_id)
            auction = json.loads(data["auction_data"])
            auction = tuple(auction.pop(column) for column in columns_auction)
            auction_bids = json.loads(data["bid_data"])
            for bid in auction_bids:
                bid["auction_id"] = bid.pop("auction_id_ssp")
                bid = tuple(bid.pop(column) for column in columns_bid)
                bids.append(bid)
            auctions.append(auction)
    return job_ids, auctions, bids

